test("shoe continues across rounds, and cut-card shuffle resets exposure exactly once", () => {
  let session = playAction(
    startRound(rig(["10", "9", "8", "9", "2", "6", "3", "10"])),
    "stand",
  );
  const firstSeen = [...session.seenIds];
  session = startRound(session);
  assert.equal(session.nextCard, 8);
  assert.deepEqual(session.seenIds.slice(0, firstSeen.length), firstSeen);
  assert.equal(session.shuffleNumber, 1);
  const old = createShoe(112, DEFAULT_RULES, 0.25);
  old.nextCard = 78;
  old.seenIds = old.cards.slice(0, 78).map((card) => card.id);
  old.runningCount = 37;
  const shuffled = startRound(old);
  assert.equal(shuffled.shuffleNumber, 2);
  assert.equal(shuffled.nextCard, 4);
  assert.equal(
    shuffled.runningCount,
    visibleCards(shuffled).reduce((sum, card) => sum + hiLo(card), 0),
  );
  assert.ok(!shuffled.seenIds.some((id) => old.seenIds.includes(id)));
});

test("a low-card tail cannot exhaust the shoe during a four-hand round at high penetration", () => {
  // This physical 52-card tail previously exhausted mid-round after three splits
  // and legal hits. A cut card at 85% alone did not protect the round at card 260.
  let session = createShoe(4, { hitSoft17: false, surrender: false }, 0.85);
  const values: Record<string, number> = { A: 1, "2": 2, "3": 3 };
  const low = session.cards
    .filter((card) => card.rank in values)
    .sort((a, b) => values[a.rank] - values[b.rank])
    .slice(0, 52);
  const first: Card[] = (["2", "3", "2", "3", "2", "2", "2"] as Rank[]).map(
    (rank) =>
      low.splice(
        low.findIndex((card) => card.rank === rank),
        1,
      )[0],
  );
  const random = seededRandom(4);
  for (let index = low.length - 1; index > 0; index--) {
    const next = Math.floor(random() * (index + 1));
    [low[index], low[next]] = [low[next], low[index]];
  }
  const tail = [...first, ...low];
  const ids = new Set(tail.map((card) => card.id));
  session.cards = [
    ...session.cards.filter((card) => !ids.has(card.id)),
    ...tail,
  ];
  session.nextCard = 260;
  session.seenIds = session.cards.slice(0, 260).map((card) => card.id);
  session.runningCount = session.cards
    .slice(0, 260)
    .reduce((sum, card) => sum + hiLo(card), 0);
  session = startRound(session);
  assert.equal(
    session.shuffleNumber,
    2,
    "shuffle before starting a round that cannot be guaranteed to finish",
  );
  if (session.round?.phase === "insurance")
    session = answerInsurance(session, false);
  for (let split = 0; split < 3; split++)
    session = playAction(session, "split");
  while (session.round?.phase === "playing")
    session = playAction(session, "hit");
  assert.equal(session.round?.phase, "complete");
  assert.ok(session.nextCard <= 312);
});

test("long seeded sessions preserve accounting, visibility, and finite-shoe invariants", () => {
  for (const hitSoft17 of [false, true]) {
    let session = createShoe(9871, { hitSoft17, surrender: true });
    let profit = 0;
    for (let round = 0; round < 160; round++) {
      session = startRound(session, 1, round);
      if (session.round?.phase === "insurance")
        session = answerInsurance(session, false);
      for (let decision = 0; session.round?.phase === "playing"; decision++) {
        assert.ok(decision < 40, "round must terminate");
        const scenario = getActiveScenario(session)!;
        session = playAction(
          session,
          recommend(scenario, session.rules).action,
          scenario.id,
        );
      }
      assert.equal(session.round?.phase, "complete");
      profit += session.round!.profit;
      assert.equal(session.bankroll, 100 + profit);
      assert.equal(session.rounds, round + 1);
      assert.equal(
        session.seenIds.length,
        session.nextCard,
        "all cards are exposed at round completion",
      );
      assert.equal(
        session.runningCount,
        visibleCards(session).reduce((sum, card) => sum + hiLo(card), 0),
      );
      assert.ok(session.nextCard <= 312);
      assert.ok(session.round!.hands.length <= 4);
    }
    assert.ok(session.shuffleNumber >= 3);
  }
});
