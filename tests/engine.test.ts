test("focused scenario generation uses the active table rules", () => {
  for (const sampling of ["balanced", "realistic"] as const) {
    for (const rules of [
      DEFAULT_RULES,
      { hitSoft17: true, surrender: true },
      DEVIATION_RULES,
      { hitSoft17: true, surrender: false },
    ]) {
      for (let seed = 0; seed < 100; seed++) {
        const doubled = generateScenario(seed, "double", sampling, [], rules);
        assert.equal(recommend(doubled, rules).action, "double");
        if (rules.surrender) {
          const surrendered = generateScenario(
            seed,
            "surrender",
            sampling,
            [],
            rules,
          );
          assert.equal(recommend(surrendered, rules).action, "surrender");
        }
      }
    }
  }
  assert.throws(
    () => generateScenario(1, "surrender", "balanced", [], DEVIATION_RULES),
    /Enable late surrender/,
  );
  for (let seed = 0; seed < 10; seed++)
    assert.doesNotThrow(() =>
      generateScenario(
        seed,
        "adaptive",
        "balanced",
        ["surrender"],
        DEVIATION_RULES,
      ),
    );
});

