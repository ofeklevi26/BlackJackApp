const hand = (ranks: Rank[]) =>
  ranks.map((rank, index) => makeCard(rank, `test-${index}`));
const strategy = (ranks: Rank[], dealer: Rank, rules = DEFAULT_RULES) =>
  recommend(makeScenario(ranks, dealer), rules).action;

/** Reorder real physical cards so edge cases have a known deal, without changing the shoe composition. */
function rig(ranks: Rank[], rules: Rules = DEFAULT_RULES): ShoeSession {
  const session = createShoe(931, rules);
  const rest = [...session.cards];
  const front: Card[] = ranks.map((rank) => {
    const index = rest.findIndex((card) => card.rank === rank);
    assert.ok(index >= 0);
    return rest.splice(index, 1)[0];
  });
  return { ...session, cards: [...front, ...rest] };
}

